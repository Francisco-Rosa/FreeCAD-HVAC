"""
Library API reference: every public name of HVACLibraryAPI and HVACLossAPI
(their `PUBLIC` sets) with its signature and docstring, and every context key
library code receives (library/contexts.py), as one Markdown page.

    python3 tools/api_reference.py           # print the page
    python3 tools/api_reference.py --write   # also rewrite docs/library-api.md

tests/test_api_reference.py fails when docs/library-api.md is out of date,
so run this with --write after changing a public method, its docstring or
a context key.
"""

import inspect
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(REPO_ROOT, "docs", "library-api.md")

# Geometry API sections, by the module each method is written in.
GEOMETRY_SECTIONS = (
    ("freecad.HVAC.library._api_ports", "Ports, vectors and lines"),
    ("freecad.HVAC.library._api_profiles", "Section wires and frames"),
    ("freecad.HVAC.library._api_solids", "Profiles and solids"),
    ("freecad.HVAC.library._api_booleans", "Booleans and shape tools"),
    ("freecad.HVAC.library._api_recipes", "Paths, fittings and layers"),
)

HEADER = """# Library API reference

<!-- Generated by tools/api_reference.py from the code; do not edit by hand. -->

Everything here is what library code (generators, PartScripts, loss and
friction functions) may use. It reaches library code through its context:
`context["hvac_api"]` is the geometry API, `context["loss_api"]` the loss
API. Library code never imports FreeCAD, Part or internal HVAC modules; how
to write a library, and what library code may do with the shapes the API
returns, is in [the library guide](library-guide.md).

A change to any public name or context key raises the matching
`API_VERSION`; a library declares the versions it was written for in its
`library.json` (`"requires_api"`) and is refused by any other (see
`CHANGELOG.md`, "Compatibility policy").
"""


def _load():
    """The two API classes and the contexts module, with the unit-test stubs standing in for FreeCAD."""
    for path in (REPO_ROOT, os.path.join(REPO_ROOT, "tests")):
        if path not in sys.path:
            sys.path.insert(0, path)
    import conftest  # noqa: F401 -- installs FreeCAD/Part stubs
    from freecad.HVAC.library import contexts
    from freecad.HVAC.library.library_api import HVACLibraryAPI
    from freecad.HVAC.library.loss_api import HVACLossAPI

    return HVACLibraryAPI, HVACLossAPI, contexts


def _entry(cls, name):
    """One public name as Markdown: its signature (or value) and its docstring."""
    member = getattr(cls, name)
    if callable(member) and not isinstance(member, type):
        try:
            signature = str(inspect.signature(member))
        except (TypeError, ValueError):
            signature = "(...)"
        title = "`{}{}`".format(name, signature)
        doc = inspect.getdoc(member) or ""
    else:
        title = "`{}`".format(name)
        doc = _constant_text(name, member)
    return "#### {}\n\n{}\n".format(title, doc.strip())


def _constant_text(name, value):
    if name == "PUBLIC":
        return "The set of public names (this page)."
    if name == "STANDARD_FITTINGS":
        return "The fitting names `build_fitting` and `measure_fitting` accept: {}.".format(
            ", ".join("`{}`".format(k) for k in sorted(value))
        )
    if name == "EPS":
        return "Length tolerance, mm: `{!r}`.".format(value)
    if isinstance(value, (int, float, str)):
        return "Value: `{!r}`.".format(value)
    if isinstance(value, (frozenset, set, tuple, list)):
        return "Values: {}.".format(", ".join("`{}`".format(v) for v in sorted(value, key=str)))
    if isinstance(value, dict):
        return "Keys: {}.".format(", ".join("`{}`".format(k) for k in sorted(value, key=str)))
    return "A {} constant.".format(type(value).__name__)


def _module_of(cls, name):
    member = getattr(cls, name)
    return getattr(getattr(member, "__func__", member), "__module__", "")


def _is_constant(cls, name):
    member = getattr(cls, name)
    return not callable(member) or isinstance(member, type)


def geometry_markdown(api):
    names = sorted(api.PUBLIC)
    lines = ["## Geometry API: `HVACLibraryAPI` (version {})\n".format(api.API_VERSION)]
    constants = [n for n in names if _is_constant(api, n)]
    lines.append("### Constants\n")
    lines.extend(_entry(api, n) for n in constants)
    placed = set(constants)
    for module, title in GEOMETRY_SECTIONS:
        members = [n for n in names if n not in placed and _module_of(api, n) == module]
        if not members:
            continue
        lines.append("### {}\n".format(title))
        lines.extend(_entry(api, n) for n in members)
        placed.update(members)
    rest = [n for n in names if n not in placed]
    if rest:
        lines.append("### Other\n")
        lines.extend(_entry(api, n) for n in rest)
    return "\n".join(lines)


def loss_markdown(loss_api):
    names = sorted(loss_api.PUBLIC)
    constants = [n for n in names if _is_constant(loss_api, n)]
    methods = [n for n in names if n not in constants]
    lines = ["## Loss API: `HVACLossAPI` (version {})\n".format(loss_api.API_VERSION)]
    lines.append("### Constants\n")
    lines.extend(_entry(loss_api, n) for n in constants)
    lines.append("### Loss functions\n")
    lines.extend(_entry(loss_api, n) for n in methods)
    return "\n".join(lines)


def contexts_markdown(contexts):
    tables = (
        ("Geometry builders and connection lengths", contexts.GEOMETRY_CONTEXT),
        ("Loss functions", contexts.LOSS_CONTEXT),
        ("Friction model factories", contexts.FRICTION_CONTEXT),
    )
    lines = [
        "## Context keys\n",
        "Each call into library code gets a `context` dict with exactly these keys",
        "(fewer when a key does not apply). `library/contexts.py` is the source.\n",
    ]
    for title, keys in tables:
        lines.append("### {}\n".format(title))
        lines.append("| Key | Meaning |")
        lines.append("|---|---|")
        lines.extend("| `{}` | {} |".format(key, text.replace("|", "\\|")) for key, text in keys.items())
        lines.append("")
    return "\n".join(lines)


def reference_markdown():
    api, loss_api, contexts = _load()
    parts = [HEADER, geometry_markdown(api), loss_markdown(loss_api), contexts_markdown(contexts)]
    return "\n".join(part.rstrip() + "\n" for part in parts)


if __name__ == "__main__":
    page = reference_markdown()
    if "--write" in sys.argv:
        os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(page)
        print("wrote", OUTPUT)
    else:
        print(page)
